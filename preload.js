'use strict';
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  getData: () => ipcRenderer.invoke('data:get'),
  getBaseData: () => ipcRenderer.invoke('data:base'),
  get: (key) => ipcRenderer.invoke('store:get', key),
  set: (key, value) => ipcRenderer.invoke('store:set', key, value),
  importDataset: () => ipcRenderer.invoke('dataset:import'),
  resetDataset: () => ipcRenderer.invoke('dataset:reset'),
  saveFile: (opts) => ipcRenderer.invoke('file:save', opts),
  openFile: (opts) => ipcRenderer.invoke('file:open', opts),
  platform: process.platform,
  getIcons: () => ipcRenderer.invoke('icons:get'),
  syncWiki: () => ipcRenderer.invoke('wiki:sync'),
  appInfo: () => ipcRenderer.invoke('app:info'),
  copyImage: (dataUrl) => ipcRenderer.invoke('image:copy', dataUrl),
  saveImage: (opts) => ipcRenderer.invoke('image:save', opts),
  checkUpdate: () => ipcRenderer.invoke('update:check'),
  installUpdate: () => ipcRenderer.invoke('update:install'),
  onUpdateProgress: (cb) => ipcRenderer.on('update:progress', (_e, p) => cb(p)),
  openExternal: (url) => ipcRenderer.send('open:external', url),
  onWikiProgress: (cb) => ipcRenderer.on('wiki:progress', (_e, p) => cb(p)),
  downloadIcons: (entries) => ipcRenderer.invoke('icons:download', entries),
  importIcons: (entries) => ipcRenderer.invoke('icons:import', entries),
  clearIcons: () => ipcRenderer.invoke('icons:clear'),
  configureStream: (cfg) => ipcRenderer.invoke('stream:configure', cfg),
  streamStatus: () => ipcRenderer.invoke('stream:status'),
  publishStream: (state) => ipcRenderer.send('stream:publish', state),
  onStreamHotkey: (cb) => ipcRenderer.on('stream:hotkey', (_e, action) => cb(action)),
  onStreamChanged: (cb) => ipcRenderer.on('stream:changed', (_e, status) => cb(status)),
  onIconProgress: (cb) => ipcRenderer.on('icons:progress', (_e, p) => cb(p)),
  minimize: () => ipcRenderer.send('win:minimize'),
  toggleMaximize: () => ipcRenderer.send('win:toggle-maximize'),
  close: () => ipcRenderer.send('win:close'),
  onWindowState: (cb) => ipcRenderer.on('win:state', (_e, state) => cb(state)),
});
